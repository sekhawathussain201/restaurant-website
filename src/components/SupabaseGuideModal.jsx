import React, { useState, useEffect } from 'react'
import { Database, Copy, Check, ExternalLink, X, RefreshCw, CheckCircle2, AlertTriangle, Code2 } from 'lucide-react'
import { testOrdersTable, SUPABASE_URL } from '../lib/supabase'

export function SupabaseGuideModal({ isOpen, onClose }) {
  const [copied, setCopied] = useState(false)
  const [testing, setTesting] = useState(false)
  const [status, setStatus] = useState(null)

  const SQL_SCRIPT = `-- 1. Create the 'orders' table for Saylani Hackathon Part A & B
CREATE TABLE IF NOT EXISTS public.orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_name TEXT NOT NULL,
    phone TEXT NOT NULL,
    address TEXT NOT NULL,
    dishes TEXT NOT NULL,
    items JSONB DEFAULT '[]'::jsonb,
    total_amount NUMERIC NOT NULL,
    status TEXT NOT NULL DEFAULT 'Pending' CHECK (status IN ('Pending', 'Preparing', 'Delivered')),
    notes TEXT DEFAULT '',
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 2. Enable Row Level Security (RLS)
ALTER TABLE public.orders ENABLE ROW LEVEL SECURITY;

-- 3. Policy: Allow anon to insert orders (Part A)
DROP POLICY IF EXISTS "Allow anon to insert orders" ON public.orders;
CREATE POLICY "Allow anon to insert orders" ON public.orders FOR INSERT TO anon, authenticated WITH CHECK (true);

-- 4. Policy: Allow reading orders (Part A & B)
DROP POLICY IF EXISTS "Allow public to view orders" ON public.orders;
CREATE POLICY "Allow public to view orders" ON public.orders FOR SELECT TO anon, authenticated USING (true);

-- 5. Policy: Allow admin status updates (Part B)
DROP POLICY IF EXISTS "Allow status update" ON public.orders;
CREATE POLICY "Allow status update" ON public.orders FOR UPDATE TO anon, authenticated USING (true) WITH CHECK (true);`

  const checkConnection = async () => {
    setTesting(true)
    const res = await testOrdersTable()
    setStatus(res)
    setTesting(false)
  }

  useEffect(() => {
    if (isOpen) {
      checkConnection()
    }
  }, [isOpen])

  if (!isOpen) return null

  const handleCopy = () => {
    navigator.clipboard.writeText(SQL_SCRIPT)
    setCopied(true)
    setTimeout(() => setCopied(false), 2000)
  }

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-black/80 backdrop-blur-md animate-fadeIn">
      <div className="relative w-full max-w-2xl glass-panel rounded-3xl p-6 sm:p-8 border border-emerald-500/40 shadow-2xl flex flex-col max-h-[92vh]">
        {/* Header */}
        <div className="flex items-center justify-between pb-4 border-b border-gray-800">
          <div className="flex items-center gap-3">
            <div className="w-10 h-10 rounded-xl bg-emerald-500/20 text-emerald-400 flex items-center justify-center">
              <Database className="w-5 h-5" />
            </div>
            <div>
              <h3 className="text-lg font-bold text-white font-['Playfair_Display']">
                Supabase Setup Assistant
              </h3>
              <p className="text-xs text-gray-400">
                Connected to project: <span className="text-emerald-400 font-mono">kpdcqcdrtoagkqiamyux</span>
              </p>
            </div>
          </div>
          <button
            onClick={onClose}
            className="p-1.5 rounded-lg text-gray-400 hover:text-white bg-gray-800/60"
          >
            <X className="w-5 h-5" />
          </button>
        </div>

        {/* Live Status Bar */}
        <div className="my-4 p-3 rounded-xl bg-gray-950/70 border border-gray-800 flex items-center justify-between text-xs">
          <div className="flex items-center gap-2">
            {testing ? (
              <RefreshCw className="w-4 h-4 text-orange-400 animate-spin" />
            ) : status?.ok ? (
              <CheckCircle2 className="w-4 h-4 text-emerald-400" />
            ) : (
              <AlertTriangle className="w-4 h-4 text-amber-400" />
            )}
            <span className="font-semibold text-gray-200">
              {testing
                ? 'Checking Supabase orders table...'
                : status?.ok
                ? 'Table "orders" is READY and active in Supabase!'
                : 'Table "orders" not detected yet in Supabase.'}
            </span>
          </div>

          <button
            onClick={checkConnection}
            disabled={testing}
            className="px-2.5 py-1 rounded bg-gray-800 hover:bg-gray-700 text-gray-300 flex items-center gap-1 cursor-pointer"
          >
            <RefreshCw className={`w-3 h-3 ${testing ? 'animate-spin' : ''}`} />
            <span>Re-check</span>
          </button>
        </div>

        {/* Instructions */}
        <div className="text-xs text-gray-300 space-y-2 mb-3">
          <p className="font-medium text-gray-200">
            To satisfy <strong className="text-emerald-400">Requirement 4</strong>, copy the SQL below, paste it into your Supabase SQL editor, and click <strong>Run</strong>:
          </p>
          <div className="flex items-center gap-3">
            <a
              href="https://supabase.com/dashboard/project/kpdcqcdrtoagkqiamyux/sql/new"
              target="_blank"
              rel="noreferrer"
              className="inline-flex items-center gap-1.5 px-3 py-1.5 rounded-lg bg-emerald-600 hover:bg-emerald-500 text-white font-bold transition-colors"
            >
              <span>Open Supabase SQL Editor</span>
              <ExternalLink className="w-3.5 h-3.5" />
            </a>

            <button
              onClick={handleCopy}
              className="inline-flex items-center gap-1.5 px-3 py-1.5 rounded-lg bg-gray-800 hover:bg-gray-700 text-orange-400 font-bold border border-gray-700 transition-colors cursor-pointer"
            >
              {copied ? <Check className="w-3.5 h-3.5 text-emerald-400" /> : <Copy className="w-3.5 h-3.5" />}
              <span>{copied ? 'Copied SQL!' : 'Copy SQL Script'}</span>
            </button>
          </div>
        </div>

        {/* Code Block */}
        <div className="flex-1 overflow-y-auto bg-gray-950 p-4 rounded-xl border border-gray-800 text-[11px] font-mono text-gray-300">
          <pre>{SQL_SCRIPT}</pre>
        </div>

        {/* Footer */}
        <div className="pt-4 mt-4 border-t border-gray-800 flex justify-between items-center text-xs">
          <span className="text-gray-400">
            Table contains: <code className="text-emerald-300">customer_name</code>, <code className="text-emerald-300">phone</code>, <code className="text-emerald-300">address</code>, <code className="text-emerald-300">dishes</code>, <code className="text-emerald-300">status</code>
          </span>
          <button
            onClick={onClose}
            className="px-4 py-2 rounded-xl bg-orange-500 hover:bg-orange-600 text-white font-bold cursor-pointer"
          >
            Done
          </button>
        </div>
      </div>
    </div>
  )
}

