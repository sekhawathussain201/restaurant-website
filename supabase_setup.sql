-- 1. Create the 'orders' table
CREATE TABLE IF NOT EXISTS public.orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_name TEXT NOT NULL,
    phone TEXT NOT NULL,
    address TEXT NOT NULL,
    dishes TEXT NOT NULL,
    items JSONB DEFAULT '[]'::jsonb,
    total_amount NUMERIC NOT NULL,
    status TEXT NOT NULL DEFAULT 'Pending' CHECK (status IN ('Pending', 'Preparing', 'Delivered')),
    notes TEXT DEFAULT '',
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 2. Enable Row Level Security (RLS)
ALTER TABLE public.orders ENABLE ROW LEVEL SECURITY;

-- 3. Policy: Allow customers (Anon public key) to insert new orders (Part A)
DROP POLICY IF EXISTS "Allow anon public to insert orders" ON public.orders;
CREATE POLICY "Allow anon public to insert orders"
ON public.orders
FOR INSERT
TO anon, authenticated
WITH CHECK (true);

-- 4. Policy: Allow anon and admin to view all orders (Part A & Part B)
DROP POLICY IF EXISTS "Allow public to view orders" ON public.orders;
CREATE POLICY "Allow public to view orders"
ON public.orders
FOR SELECT
TO anon, authenticated
USING (true);

-- 5. Policy: Allow admin / authenticated users to update order status (Part B)
DROP POLICY IF EXISTS "Allow public to update order status" ON public.orders;
CREATE POLICY "Allow public to update order status"
ON public.orders
FOR UPDATE
TO anon, authenticated
USING (true)
WITH CHECK (true);

